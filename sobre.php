    <h1>Sobre a farmácia SWAG</h1>
    <h2>O projeto de desenvolvimento de um sistema de uma farmácia tem o intuito de facilitar o controle de vendas, estoque, clientes, compras, fornecedores e entre outras funcionalidades. Tal projeto será utilizado apenas dados fictícios pois tem a finalidade apenas de exercitar a nossa compreensão em PHP, MySQL e outras ferramentas que serão utilizadas no projeto. 

    <br>
    Temos com objetivo a criação de um sistema funcional que permita um maior planejamento e organização das informações. Inicialmente será realizado um sistema para cadastramento de usuários, medicamentos, profissionais utilizando banco de dados. Após a criação e elaboração do banco de dados iriamos para parte do desenvolvimento da página e design do site. Também como segundo plano temos a ideia a criação de relatórios de vendas e compras.
    
    <br>
    Os fundadores do projeto Samuel Santos de Lima, Heliab Diogo Oliveira Sacramento e Mizael observaram o quão necessário é a criação de tal sistema não apenas ao mercado financeiro mas aos usuários.</h2>
